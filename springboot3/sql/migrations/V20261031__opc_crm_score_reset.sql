-- V20261031 · CRM 商机的「编造评分」归零
--
-- 背景:
--   商机看板(opc_crm_opportunity)的卡片上挂着一个「LLM 评分」。
--   那个评分此前**根本调不通** —— opc-crm 的 AiCoreGateway 指向
--   POST /opc/ai-core/opportunity/score,而这个端点在 opc-ai-core 里从来不存在
--   (对端只有 /opc/llm/chat 和 /opc/llm/models);
--   加上 @FeignClient 上写了 url,Nacos 服务发现被绕过,base-url 里的主机名
--   (opc-ai-core)在容器网里也解析不了。
--   也就是说:系统里**没有任何一条代码路径**能产出一个商机评分。
--
--   可看板上每张卡片却都显示着 85 / 70 / 95 这样的分数 —— 全部来自
--   deploy/mysql-initdb.d/95-opc-crm-seed.sql 的种子 INSERT,理由(score_reason)留空。
--   这跟市场页那批「823 次浏览 / 4.8 分 127 条评价」是同一种病:
--   演示环境在展示一个自己造出来的数字。
--
-- 处理:
--   把「有分没理由」的记录归零 —— 真实起点是「还没评过」(score=0, reason 为空),
--   点一次「LLM 评分」才长出一个有出处的分数。
--
-- 为什么条件是「有分**且**没理由」而不是「有分」:
--   修复后的评分路径**分数和理由同生共死** —— 分数和 score_reason 一定是一起写的。
--   所以「有分没理由」只可能来自种子/手工造的数据,真实评分不可能落在这个条件里。
--   这样这条迁移以后再跑也只会碰到该碰的行,不会误伤真实评分。
--
-- 幂等:可重复执行(归零后 score=0,不再命中 WHERE)。
-- ============================================================

UPDATE opc_crm_opportunity
SET score = 0
WHERE score <> 0
  AND score_reason IS NULL;
